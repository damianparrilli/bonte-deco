-- 1) Usuarios autorizados a editar (agregá una línea por persona)
create table if not exists public.admins (email text primary key);
insert into public.admins (email) values
  ('TU_EMAIL@ejemplo.com')
on conflict do nothing;

-- ¿El usuario logueado está autorizado?
create or replace function public.es_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.admins a where lower(a.email) = lower(coalesce(auth.jwt() ->> 'email', '')));
$$;
grant execute on function public.es_admin() to anon, authenticated;

-- 2) Tablas
create table if not exists public.productos (
  id uuid primary key default gen_random_uuid(),
  nombre text not null,
  categoria text not null default '',
  subcategoria text not null default '',
  tela text not null default '',
  descripcion text not null default '',
  fotos jsonb not null default '[]'::jsonb,
  peso text not null default '',
  alto text not null default '',
  ancho text not null default '',
  profundidad text not null default '',
  orden bigint not null default 0,
  actualizado timestamptz not null default now()
);

create table if not exists public.variantes (
  id uuid primary key default gen_random_uuid(),
  producto_id uuid not null references public.productos(id) on delete cascade,
  codigo text not null,
  color text not null default '',
  medida text not null default '',
  detalle text not null default '',
  efectivo numeric(12,2),
  lista numeric(12,2),          -- vacío = efectivo + recargo
  oferta text not null default '',
  stock integer,                -- vacío = sin límite
  publicar boolean not null default true,
  orden integer not null default 0
);
create unique index if not exists variantes_codigo_unico on public.variantes (upper(codigo));
create index if not exists variantes_producto on public.variantes (producto_id);

create table if not exists public.config (clave text primary key, valor jsonb not null);
insert into public.config (clave, valor) values ('recargo', '20') on conflict do nothing;

-- 3) Seguridad (Row Level Security)
alter table public.admins enable row level security;     -- sin políticas: solo se edita desde acá
alter table public.productos enable row level security;
alter table public.variantes enable row level security;
alter table public.config enable row level security;

drop policy if exists "leer productos" on public.productos;
create policy "leer productos" on public.productos for select using (true);
drop policy if exists "editar productos" on public.productos;
create policy "editar productos" on public.productos for all to authenticated using (public.es_admin()) with check (public.es_admin());

drop policy if exists "leer variantes" on public.variantes;
create policy "leer variantes" on public.variantes for select using (publicar or public.es_admin());
drop policy if exists "editar variantes" on public.variantes;
create policy "editar variantes" on public.variantes for all to authenticated using (public.es_admin()) with check (public.es_admin());

drop policy if exists "leer config" on public.config;
create policy "leer config" on public.config for select using (true);
drop policy if exists "editar config" on public.config;
create policy "editar config" on public.config for all to authenticated using (public.es_admin()) with check (public.es_admin());

-- 4) Fotos (bucket público: cualquiera ve las fotos, solo admins suben/borran)
insert into storage.buckets (id, name, public) values ('fotos', 'fotos', true) on conflict (id) do nothing;
drop policy if exists "subir fotos" on storage.objects;
create policy "subir fotos" on storage.objects for insert to authenticated with check (bucket_id = 'fotos' and public.es_admin());
drop policy if exists "cambiar fotos" on storage.objects;
create policy "cambiar fotos" on storage.objects for update to authenticated using (bucket_id = 'fotos' and public.es_admin());
drop policy if exists "borrar fotos" on storage.objects;
create policy "borrar fotos" on storage.objects for delete to authenticated using (bucket_id = 'fotos' and public.es_admin());

